const dicts: Record<Lang, Dict> = { ar, en };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dicts[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const { lang } = useSettings();
  const t = (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { t, lang, dir: lang === "ar" ? ("rtl" as const) : ("ltr" as const) };
}

export function formatDate(ts: number, lang: Lang) {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-EG" : "en-GB", { day: "numeric", month: "short" }).format(ts);
}

export function num(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "ar" ? "ar-EG" : "en-US").format(n);
}
