const sleep = (ms: number, signal?: AbortSignal) =>
  new Promise<void>((resolve, reject) => {
    const id = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => (clearTimeout(id), reject(new DOMException("aborted", "AbortError"))));
  });

function pickText(task: string, history?: ChatMsg[]) {
  if (history?.length) {
    const q = history[history.length - 1].content;
    return `سؤال حلو! 👌 بالنسبة لـ «${q}»:\n\nمن الدرس، أهم 3 نقط:\n1. **الخلية** وحدة البناء والوظيفة.\n2. **الميتوكوندريا** بتنتج الطاقة (ATP).\n3. **الخلية النباتية** فيها جدار خلوي وبلاستيدات خضراء.\n\n_(ده رد تجريبي في نسخة المعاينة.)_`;
  }
  if (task.includes("as if to a student who finds it hard")) return EXPLAIN;
  const style = /brief/.test(task) && /Keep it tight/.test(task) ? "brief" : /exam/.test(task) && /revision sheet/.test(task) ? "exam" : "detailed";
  return summary(style);
}

export async function demoStream(opts: { task: string; history?: ChatMsg[]; onText: (s: string) => void; signal?: AbortSignal }) {
  const text = pickText(opts.task, opts.history);
  await sleep(500, opts.signal);
  let out = "";
  for (const piece of text.match(/[\s\S]{1,12}/g) ?? []) {
    out += piece;
    opts.onText(out);
    await sleep(18, opts.signal);
  }
  return out;
}

export async function demoJson<T>(schema: Record<string, unknown>, signal?: AbortSignal): Promise<T> {
  await sleep(900, signal);
  const key = (schema.required as string[])[0] as keyof typeof json;
  return structuredClone(json[key]) as T;
}

